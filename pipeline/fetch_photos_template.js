/*
  fetch_photos.js  (generated by build_players.py from fetch_photos_template.js; do not edit the generated copy)
  Downloads a small portrait photo and its licence details for every answer-pool player, from the
  lead image on each player's English Wikipedia page (free-licensed images only).

  How to run
    1. Open any page on https://www.wikidata.org in Chrome (any Wikimedia site works; if Chrome has
       blocked downloads from one, use another)
    2. Press F12, open the Console tab, paste this whole file, press Enter
    3. Wait a few minutes. Progress prints in the console.
    4. cricle_photos_raw.json downloads when it's finished. If nothing downloads, click anywhere on
       the page, then type  __cricketPhotos.save()  in the console and press Enter.
    5. python build_players.py --raw data/cricket_wiki_raw.json --cricsheet --photos data/cricle_photos_raw.json
*/
(async () => {
  const TITLES = /*TITLES*/[];
  const API = "https://en.wikipedia.org/w/api.php";
  const HEADERS = { "Api-User-Agent": "CricleDataBuilder/1.0 (browser fetch)" };
  const THUMB_REQUEST = 330;          // a standard Wikimedia thumbnail width
  const OUT_W = 240, OUT_H = 300;     // stored portrait size (4:5)

  const S = (window.__cricketPhotos = { status: "running", step: "starting", errors: [] });
  const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
  const log = (m) => { S.step = m; console.log("[cricle photos] " + m); };

  async function api(params) {
    const q = new URLSearchParams({ format: "json", formatversion: "2", maxlag: "5", origin: "*", ...params });
    const url = (params.__base || API);
    q.delete("__base");
    if (!q.get("maxlag")) q.delete("maxlag");
    for (let attempt = 0; attempt < 6; attempt++) {
      let r;
      try { r = await fetch(url + "?" + q, { headers: HEADERS }); } catch { await sleep(2000 * 2 ** attempt); continue; }
      if (r.status === 429 || r.status >= 500) { await sleep(2000 * 2 ** attempt); continue; }
      const j = await r.json();
      if (j.error && j.error.code === "maxlag") { await sleep(5000); continue; }
      if (j.error) throw new Error(JSON.stringify(j.error));
      return j;
    }
    throw new Error("Gave up: " + q);
  }

  const strip = (html) => {
    const d = document.createElement("div");
    d.innerHTML = html || "";
    return d.textContent.replace(/\s+/g, " ").trim();
  };

  async function toJpegBase64(url) {
    for (let attempt = 0; attempt < 4; attempt++) {
      const r = await fetch(url, { mode: "cors" });
      if (r.status === 429 || r.status >= 500) { await sleep(3000 * 2 ** attempt); continue; }
      if (!r.ok) throw new Error("HTTP " + r.status);
      const bmp = await createImageBitmap(await r.blob());
      const target = OUT_W / OUT_H;
      let sx = 0, sy = 0, sw = bmp.width, sh = bmp.height;
      if (bmp.width / bmp.height > target) { sw = bmp.height * target; sx = (bmp.width - sw) / 2; }
      else { sh = bmp.width / target; sy = (bmp.height - sh) * 0.2; }   // keep the top, where faces are
      const c = document.createElement("canvas");
      c.width = OUT_W; c.height = OUT_H;
      const g = c.getContext("2d");
      g.imageSmoothingQuality = "high";
      g.drawImage(bmp, sx, sy, sw, sh, 0, 0, OUT_W, OUT_H);
      const blob = await new Promise((res) => c.toBlob(res, "image/jpeg", 0.82));
      const b64 = await new Promise((res) => { const fr = new FileReader(); fr.onload = () => res(fr.result.split(",")[1]); fr.readAsDataURL(blob); });
      return { jpg: b64, cropped: sw !== bmp.width || sh !== bmp.height };
    }
    throw new Error("Gave up on image " + url);
  }

  function save(out) {
    const blob = new Blob([JSON.stringify(out)], { type: "application/json" });
    const a = document.createElement("a");
    a.href = URL.createObjectURL(blob);
    a.download = "cricle_photos_raw.json";
    document.body.appendChild(a); a.click(); a.remove();
  }

  const out = (S.out = { fetched_utc: new Date().toISOString(), source: "fetch_photos.js v1", photos: {}, missing: [], errors: S.errors });
  S.save = () => save(out);

  try {
    // 1. Lead image of each page (free licences only), following redirects back to the requested title
    const lead = {};
    for (let i = 0; i < TITLES.length; i += 50) {
      const batch = TITLES.slice(i, i + 50);
      const j = await api({ action: "query", prop: "pageimages", piprop: "thumbnail|name", pithumbsize: String(THUMB_REQUEST),
                            pilicense: "free", redirects: "1", titles: batch.join("|") });
      const back = {};
      for (const n of j.query?.normalized || []) back[n.to] = n.from;
      for (const r of j.query?.redirects || []) back[r.to] = back[r.from] || r.from;
      for (const p of j.query?.pages || []) {
        const asked = back[p.title] || p.title;
        if (p.thumbnail && p.pageimage) lead[asked] = { file: p.pageimage, thumb: p.thumbnail.source };
      }
      log(`lead images ${Math.min(i + 50, TITLES.length)}/${TITLES.length}`);
    }

    // 1b. Pages with no free lead image: try the player's Wikidata photo (P18), always a Commons file
    const noLead = TITLES.filter((t) => !lead[t]);
    const qids = {};
    for (let i = 0; i < noLead.length; i += 50) {
      const j = await api({ action: "query", prop: "pageprops", ppprop: "wikibase_item", redirects: "1", titles: noLead.slice(i, i + 50).join("|") });
      const back = {};
      for (const n of j.query?.normalized || []) back[n.to] = n.from;
      for (const r of j.query?.redirects || []) back[r.to] = back[r.from] || r.from;
      for (const p of j.query?.pages || []) if (p.pageprops?.wikibase_item) qids[back[p.title] || p.title] = p.pageprops.wikibase_item;
    }
    const qlist = Object.entries(qids), p18 = {};
    for (let i = 0; i < qlist.length; i += 50) {
      const j = await api({ __base: "https://www.wikidata.org/w/api.php", action: "wbgetentities", ids: qlist.slice(i, i + 50).map((x) => x[1]).join("|"), props: "claims", maxlag: "" });
      for (const [t, q] of qlist.slice(i, i + 50)) { const v = j.entities?.[q]?.claims?.P18?.[0]?.mainsnak?.datavalue?.value; if (v) p18[t] = v.replace(/ /g, "_"); }
    }
    log(`Wikidata photos for ${Object.keys(p18).length} of ${noLead.length} pages without a lead image`);

    // 2. Licence, author and (for Wikidata photos) a thumbnail for each file
    const thumbs = {};
    const files = [...new Set([...Object.values(lead).map((x) => x.file), ...Object.values(p18)])];
    const meta = {};
    for (let i = 0; i < files.length; i += 50) {
      const j = await api({ action: "query", prop: "imageinfo", iiprop: "extmetadata|url", iiurlwidth: String(THUMB_REQUEST),
                            iiextmetadatafilter: "Artist|LicenseShortName|LicenseUrl|AttributionRequired|Credit",
                            titles: files.slice(i, i + 50).map((f) => "File:" + f).join("|") });
      const back = {};
      for (const n of j.query?.normalized || []) back[n.to] = n.from;
      for (const p of j.query?.pages || []) {
        const ii = p.imageinfo?.[0];
        if (!ii) continue;
        const em = ii.extmetadata || {};
        const name = (back[p.title] || p.title).replace(/^File:/, "");
        meta[name] = { artist: strip(em.Artist?.value), license: strip(em.LicenseShortName?.value),
                       license_url: em.LicenseUrl?.value || null, desc_url: ii.descriptionurl || null };
        if (ii.thumburl) thumbs[name] = ii.thumburl;
      }
      log(`licences ${Math.min(i + 50, files.length)}/${files.length}`);
    }

    // 3. Download, crop to a 4:5 portrait and re-encode small
    let k = 0;
    for (const t of TITLES) {
      k++;
      const l = lead[t] || (p18[t] && thumbs[p18[t]] ? { file: p18[t], thumb: thumbs[p18[t]], source: "wikidata" } : null);
      if (!l) { out.missing.push(t); continue; }
      try {
        const img = await toJpegBase64(l.thumb);
        out.photos[t] = { file: l.file, ...(meta[l.file] || {}), ...img, source: l.source || "wikipedia" };
      } catch (e) {
        S.errors.push(`${t}: ${e}`);
        out.missing.push(t);
      }
      if (k % 25 === 0) log(`photos ${k}/${TITLES.length}`);
      await sleep(120);
    }
    S.summary = { players: TITLES.length, photos: Object.keys(out.photos).length, missing: out.missing.length, errors: S.errors.length };
    S.status = "done";
    log("done: " + JSON.stringify(S.summary));
    if (!window.__cricketNoAutoSave) save(out);
  } catch (e) {
    S.status = "error"; S.errors.push(String(e)); log("error: " + e);
  }
})();
